import type { BaseDocument, YearMonth, IsoTimestamp } from './common.js';

export const EmploymentType = {
  SALARIED: 'SALARIED',
  PER_SESSION: 'PER_SESSION',
} as const;
export type EmploymentType = (typeof EmploymentType)[keyof typeof EmploymentType];

export const PayrollRunStatus = {
  DRAFT: 'DRAFT',
  APPROVED: 'APPROVED',
  PAID: 'PAID',
} as const;
export type PayrollRunStatus = (typeof PayrollRunStatus)[keyof typeof PayrollRunStatus];

export interface StaffDocument extends BaseDocument {
  id: string;
  staffCode: string;
  name: string;
  phone: string | null;
  email: string | null;
  authUid: string | null;
  centreIds: string[];
  employmentType: EmploymentType;
  /** Monthly basic salary in paise (salaried) or per-session rate in paise (per-session). */
  ratePaise: number;
  bankAccountLast4: string | null;
  upiId: string | null;
  dateOfJoining: string | null;
  status: 'ACTIVE' | 'INACTIVE';
}

export interface PayrollRunDocument extends BaseDocument {
  id: string;
  staffId: string;
  staffName: string;
  centreIds: string[];
  month: YearMonth;
  employmentType: EmploymentType;

  sessionsCount: number;
  basicPaise: number;
  perSessionPayPaise: number;
  allowancesPaise: number;

  professionalTaxPaise: number;
  tdsPaise: number;
  advanceRecoveryPaise: number;
  otherDeductionsPaise: number;

  grossPayPaise: number;
  totalDeductionsPaise: number;
  netPayPaise: number;

  status: PayrollRunStatus;
  approvedBy: string | null;
  approvedAt: IsoTimestamp | null;
  paymentRef: string | null;
  paidAt: IsoTimestamp | null;
  notes: string | null;
  /** Built from saved registers by the payroll job. */
  autoGenerated?: boolean;
  /** Batch name → sessions credited, for auto-generated runs. */
  sessionBreakdown?: Record<string, number> | null;
  generatedAt?: IsoTimestamp | null;
}

// ── Payroll from attendance ─────────────────────────────────────────────────

/** Auto-generated runs use a fixed id, so regenerating updates instead of duplicating. */
export function autoPayrollRunId(staffId: string, month: string): string {
  return `${staffId}_${month}`;
}

/**
 * Pay for a month from the sessions a coach took registers for.
 * PER_SESSION: sessions × rate. SALARIED: the monthly salary (sessions shown
 * for reference). Allowances and deductions are whatever the admin entered on
 * the draft — regeneration keeps them.
 */
export function computeAttendancePayroll(input: {
  employmentType: EmploymentType;
  ratePaise: number;
  sessionsCount: number;
  allowancesPaise?: number;
  deductionsPaise?: {
    professionalTaxPaise?: number;
    tdsPaise?: number;
    advanceRecoveryPaise?: number;
    otherDeductionsPaise?: number;
  };
}) {
  const basicPaise = input.employmentType === 'SALARIED' ? input.ratePaise : 0;
  const perSessionPayPaise = input.employmentType === 'PER_SESSION' ? input.ratePaise * input.sessionsCount : 0;
  const allowancesPaise = input.allowancesPaise ?? 0;
  const d = input.deductionsPaise ?? {};
  const totalDeductionsPaise = (d.professionalTaxPaise ?? 0) + (d.tdsPaise ?? 0)
    + (d.advanceRecoveryPaise ?? 0) + (d.otherDeductionsPaise ?? 0);
  const grossPayPaise = basicPaise + perSessionPayPaise + allowancesPaise;
  return { basicPaise, perSessionPayPaise, allowancesPaise, grossPayPaise, totalDeductionsPaise, netPayPaise: grossPayPaise - totalDeductionsPaise };
}

/**
 * Who a session's pay goes to — exactly one person.
 *
 * The coach who FIRST saved the register (takenBy). If an admin or manager
 * saved it on a coach's behalf, the batch's assigned coach, when there is
 * exactly one. Sessions saved before takenBy existed fall back to whoever
 * opened them. Crediting everyone in coachIds paid two coaches for one
 * session whenever one opened and another saved or corrected it.
 */
export function creditedCoachUid(
  session: { takenBy?: string | null; takenByRole?: string | null; coachIds?: readonly string[] | null },
  batchCoachIds: readonly string[],
): string | null {
  if (session.takenBy) {
    if (session.takenByRole && session.takenByRole !== 'COACH') {
      return batchCoachIds.length === 1 ? batchCoachIds[0] : null;
    }
    return session.takenBy;
  }
  return session.coachIds?.[0] ?? null;
}
